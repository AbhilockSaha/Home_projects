def num_text(n):
    n = str(n)
    for i in n:
        if i == "0":
            print("zero")
        elif i == "1":
            print("One")
        elif i == "2":
            print("Two")
        elif i == "3":
            print("Three")       
        elif i == "4":
            print("Four")
        elif i == "5":
            print("Five")
        elif i == "6":
            print("Six")
        elif i == "7":
            print("Seven")
        elif i == "8":
            print("Eight")
        elif i == "9":
            print("Nine")                                                        
x = 1900
num_text(x)